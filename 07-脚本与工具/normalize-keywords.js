// Apply keywords to each unit file
let updated = 0;
Object.entries(keywordMap).forEach(([unitId, keywords]) => {
  // Find the file
  const prefix = unitId.split('-')[0];
  const dir = path.join('02-内容单元库', prefix);
  if (!fs.existsSync(dir)) return;
  const files = fs.readdirSync(dir).filter(f => f.startsWith(unitId + '_') && f.endsWith('.md'));
  if (files.length === 0) {
    console.log('NOT FOUND: ' + unitId);
    return;
  }
  const filePath = path.join(dir, files[0]);
  let content = fs.readFileSync(filePath, 'utf8');

  // Replace keywords section
  const newKeywords = 'keywords:\n' + keywords.map(k => '  - ' + k).join('\n');
  const oldKwPattern = /^keywords:\s*\r?\n([\s\S]*?)(?=\r?\n\S|\r?\n?$)/m;
  content = content.replace(oldKwPattern, newKeywords + '\n');

  fs.writeFileSync(filePath, content, 'utf8');
  console.log('KW: ' + files[0] + ' → ' + keywords.length + '词');
  updated++;
});

console.log('\n更新完成: ' + updated + '个文件');
